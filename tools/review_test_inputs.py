"""Dev tool: review every file in test-inputs/ and write readable scorecards to test-outputs/.

Usage:
    python tools/review_test_inputs.py [--force]

Intermediate files (PDF, page images, JSON) go to .cache/work/<name>-<ext>/ and are reused
when inputs are unchanged. test-outputs/ gets one <input file name>.md per input (the scorecard,
or the error message if the file can't be reviewed) plus index.md. Judged items are only
included if a judgments.json is present in the work folder.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "skill" / "slide-poster-review" / "scripts"))
import contrast  # noqa: E402
import extract_text  # noqa: E402
import font_size  # noqa: E402
import ocr  # noqa: E402
import render  # noqa: E402
import scorecard  # noqa: E402

INPUTS = ROOT / "test-inputs"
WORK = ROOT / ".cache" / "work"
OUTPUTS = ROOT / "test-outputs"
TYPES = {".pptx", ".pdf", ".odp", ".ppt", ".pptm", ".docx"}


def review(src: Path, force: bool) -> tuple[str, str]:
    """(scorecard markdown, one-line status for the index)."""
    try:
        d = render.render(src, WORK, force=force)
    except render.RenderError as e:
        return (f"# Not reviewed: {src.name}\n\n{e}\n", f"not reviewed: {str(e).split('. ')[0]}")
    extract_text.extract(d)
    ocr.run(d)
    font_size.measure(d)
    contrast.measure(d)
    md = scorecard.build(d).read_text(encoding="utf-8")
    sc = json.loads((d / "scorecard.json").read_text(encoding="utf-8"))
    return md, f"{sc['overall']:.1f} of 4 ({sc['items_assessed']} of {sc['items_total']} items)"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--force", action="store_true", help="re-render even if cached")
    a = ap.parse_args()
    OUTPUTS.mkdir(exist_ok=True)
    rows = []
    for src in sorted(p for p in INPUTS.iterdir() if p.suffix.lower() in TYPES):
        md, status = review(src, a.force)
        out = OUTPUTS / f"{src.name}.md"
        out.write_text(md, encoding="utf-8")
        rows.append(f"| [{src.name}]({out.name.replace(' ', '%20')}) | {status} |")
        print(f"{src.name}: {status}")
    index = ["# Test scorecards", "",
             "Generated by `tools/review_test_inputs.py`. Overall scores cover assessed items only.", "",
             "| Input | Overall |", "|---|---|", *rows, ""]
    (OUTPUTS / "index.md").write_text("\n".join(index), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
